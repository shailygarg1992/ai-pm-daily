// Inlines web/index.html into agent/lib/home-html.ts so the agent serves its own
// phone-first chat page at "/". Re-run after editing web/index.html:
//   npm run build-home
import { readFileSync, writeFileSync } from "node:fs";
const html = readFileSync(new URL("../web/index.html", import.meta.url), "utf8");
writeFileSync(
  new URL("../agent/lib/home-html.ts", import.meta.url),
  `// Generated by scripts/build-home.mjs from web/index.html. Do not edit by hand.\nexport const HOME_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`home page: ${html.length} bytes`);
