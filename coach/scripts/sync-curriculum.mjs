// Copies the app's curriculum (src/data.js) into the agent so the coach teaches
// exactly what the app teaches. Re-run after editing src/data.js:
//   npm run sync-curriculum
import { writeFileSync } from "node:fs";
import { DAYS, COMPANIES, HOT_TOOLS } from "../../src/data.js";

const days = DAYS.map((d) => ({
  day: d.day,
  theme: d.theme,
  briefing: d.briefing.map((b) => ({
    text: b.text,
    advancedText: b.advancedText,
    example: b.example,
    advancedExample: b.advancedExample,
  })),
  quiz: d.quiz.map((q) => ({
    question: q.question,
    options: q.options,
    answer: q.answer,
    advancedQuestion: q.advancedQuestion,
    advancedOptions: q.advancedOptions,
    advancedAnswer: q.advancedAnswer,
    learnLinks: q.learnLinks ?? [],
  })),
}));

const out = `// Generated by scripts/sync-curriculum.mjs from ../src/data.js. Do not edit by hand.
export const DAYS = ${JSON.stringify(days, null, 2)} as const;
export const COMPANIES = ${JSON.stringify(COMPANIES.map(({ id, name, tagline }) => ({ id, name, tagline })), null, 2)} as const;
export type QuizItem = (typeof DAYS)[number]["quiz"][number];
export const HOT_TOOLS = ${JSON.stringify(HOT_TOOLS.map(({ name, category, description, whyItMatters }) => ({ name, category, description, whyItMatters })), null, 2)} as const;
`;
writeFileSync(new URL("../agent/lib/curriculum.ts", import.meta.url), out);
console.log(`Synced ${days.length} days, ${days.reduce((n, d) => n + d.quiz.length, 0)} quiz questions.`);
